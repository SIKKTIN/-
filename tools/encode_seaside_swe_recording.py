"""Encode native framebuffer captures, without editing any artwork."""
from pathlib import Path
import hashlib
import json
from PIL import Image

root = Path(__file__).resolve().parents[1]
doc = root / 'docs/art/seaside-swe-v1'
paths = [doc / 'frames' / f'{i:03d}.png' for i in range(60)]
assert all(path.is_file() for path in paths)
report = json.loads((doc / 'checks.json').read_bytes())
assert all(report['checks'].values()), report['checks']
frames = [Image.open(path) for path in paths]
frames[0].save(doc / 'water-simulation.webp', format='WEBP', save_all=True,
               append_images=frames[1:], duration=100, loop=0, quality=85, method=4)
with Image.open(doc / 'water-simulation.webp') as recording:
    assert recording.n_frames == 60
for frame in frames:
    frame.close()
provenance = json.loads((root / 'art/fx/seaside_swe_v1/provenance.json').read_bytes())
report['map_unchanged_during_sample_work'] = (hashlib.sha256((root / 'data/rooms/r04.json').read_bytes()).hexdigest()
                                           == provenance['map_sha256_at_start'])
report['recording'] = {'path': str(doc / 'water-simulation.webp'), 'frames': 60,
                       'duration_seconds': 6, 'origin': 'native Godot framebuffer',
                       'simulation_seconds_per_frame': 0.1}
(doc / 'checks.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
delivery = {'status': 'standalone numerical simulation prototype verified',
            'upstream': provenance['upstream'], 'commit': provenance['commit'],
            'engine': 'Godot 4.7.2 / Forward+ / D3D12',
            'checks': report['checks'], 'performance': report['performance'],
            'device': report['device'], 'map_unchanged': report['map_unchanged_during_sample_work'],
            'preview': str(doc / 'water-simulation.webp'),
            'scene': str(root / 'scenes/prototypes/seaside_swe_demo.tscn'),
            'integration_plan': [
                'Use a reusable Node2D water region and Texture2DRD state output behind pier and coastline sprites.',
                'Generate local bathymetry and solid masks from coastline, rocks and pier positions.',
                'Maintain a fixed physical extent and simulate only the visible coastal patch with an outside margin.',
                'Keep the 120 Hz fixed step and avoid runtime GPU-to-CPU readback; suspend fully offscreen patches.',
                'Validate map-level frame pacing before adding FFT offshore detail or splash particles.',
            ],
            'limitations': [
                'Heightfield cannot represent overturning wave geometry; airborne spray requires particles.',
                'Terrain and pier are procedural technical placeholders, not final game artwork.',
                'Standalone timings are not a benchmark of the entire game.',
                'Main game scene, live map and existing map editor were not modified.',
            ]}
(doc / 'delivery.json').write_text(json.dumps(delivery, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
# Only remove the exact screenshots generated by this capture; no recursive deletion.
for path in paths:
    path.unlink()
try:
    (doc / 'frames').rmdir()
except OSError:
    pass
print('Encoded six-second simulation recording; numerical checks passed.')
